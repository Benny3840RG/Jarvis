/**
 * Generates the voice-intent baseline evidence report (#567).
 *
 * Reproducible: it imports the pure scorer, runs it against the live parser,
 * and writes a dated Markdown report under `docs/evidence/`. Run with:
 *
 *   cd typescript
 *   node --import tsx tests/support/generateVoiceIntentReport.ts
 *
 * It writes no production state and takes no arguments. The committed report
 * identifies the input source files by content, independent of Git HEAD.
 */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { evaluate, formatPct, type EvaluationReport } from "./voiceIntentScoring.js";

// This is the baseline edition, not the time of regeneration.
const BASELINE_EDITION = "2026-11-10";
const TYPESCRIPT_ROOT = new URL("../../", import.meta.url);
const INPUT_SOURCES = [
  "src/voice/voiceParser.ts",
  "src/voice/voiceCommands.ts",
  "tests/support/voiceIntentDataset.ts",
  "tests/support/voiceIntentScoring.ts",
  "tests/support/generateVoiceIntentReport.ts",
] as const;

function sourceRows(): string {
  return INPUT_SOURCES.map((source) => {
    const bytes = readFileSync(new URL(source, TYPESCRIPT_ROOT));
    const digest = createHash("sha256").update(bytes).digest("hex");
    return `| \`${source}\` SHA-256 | \`${digest}\` |`;
  }).join("\n");
}

function categoryTable(report: EvaluationReport): string {
  const rows = report.byCategory.map((t) => {
    const cells = [
      t.category,
      String(t.total),
      String(t.correct),
      String(t.missed),
      String(t.wrongMatch),
      String(t.withheld),
      String(t.leaked),
    ];
    return `| ${cells.join(" | ")} |`;
  });
  return [
    "| Category | Cases | Correct | Missed | Wrong-match | Withheld | Leaked |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function missedExamples(report: EvaluationReport, limit = 12): string {
  const missed = report.results.filter(
    (r) =>
      r.verdict === "missed" &&
      (r.case.category === "informal-au" || r.case.category === "asr-error"),
  );
  const lines = missed
    .slice(0, limit)
    .map(
      (r) =>
        `- \`${r.case.profile}\` · "${r.case.transcript}" → **${r.status}** (intended \`${r.case.expectedCommandId}\`)`,
    );
  return lines.join("\n");
}

export function buildMarkdown(report: EvaluationReport): string {
  const natural = report.naturalCoverage;
  const naturalMisses = report.byCategory
    .filter(({ category }) => category === "informal-au" || category === "asr-error")
    .reduce((sum, { missed }) => sum + missed, 0);
  const gap = formatPct(natural.total === 0 ? 0 : naturalMisses / natural.total);
  const safetyClean =
    report.wrongMatches.length === 0 &&
    report.safetyLeaks.length === 0 &&
    report.unsafeActuations.length === 0;

  return `# Voice-intent baseline — evidence (#567)

> Generated by \`typescript/tests/support/generateVoiceIntentReport.ts\`. Do not
> hand-edit; regenerate to refresh. This is an **evaluation** artefact — it
> changes no production behaviour and commissions nothing.

## Provenance

| Field | Value |
| --- | --- |
| Baseline edition | ${BASELINE_EDITION} |
| Dataset version | ${report.datasetVersion ?? "custom (unversioned)"} |
${sourceRows()}
| Parser under test | \`src/voice/voiceParser.ts\` (\`parseUtterance\`, exact whole-utterance, final-only) |
| Model/provider | none — the parser is pure and deterministic; no model call |
| Evaluation method | deterministic classification by \`tests/support/voiceIntentScoring.ts\` |

## What this measures

The guarded parser recognises an utterance only when, after light
normalisation, it **equals a catalog phrase in full**. That strictness is the
safety boundary (final-only dispatch, no substring smuggling, fail-closed on
ambiguity). This baseline quantifies the **coverage gap** a future
natural-language layer would need to close *ahead of* that boundary — never
through it — and confirms the safety invariants still hold.

Metrics are reported **separately**, per the commission:

- **Intent accuracy** — a clear single intent resolved to the right command.
- **Coverage gap (clarification)** — a clear intent the parser declines today
  (safe; this is the work Wave One would do).
- **Unsafe assumptions** — a wrong command resolved, or any command resolved
  when none was intended. **Must be zero.**

## Headline results

- **Total cases:** ${report.totalCases}
- **Canonical anchors recognised:** ${report.canonicalCoverage.correct}/${report.canonicalCoverage.total} (${formatPct(report.canonicalCoverage.rate)}) — dataset labels agree with the live catalog.
- **Natural-phrasing coverage:** ${natural.correct}/${natural.total} = **${formatPct(natural.rate)}** correctly recognised.
  - dev split: ${report.naturalCoverageDev.correct}/${report.naturalCoverageDev.total} (${formatPct(report.naturalCoverageDev.rate)})
  - held-out split: ${report.naturalCoverageHeldOut.correct}/${report.naturalCoverageHeldOut.total} (${formatPct(report.naturalCoverageHeldOut.rate)})
- **Coverage gap on natural phrasing:** ${naturalMisses}/${natural.total} = **${gap}** of natural utterances were declined (safe, but unserved).
- **Unsafe assumptions:** wrong-matches **${report.wrongMatches.length}**, safety leaks **${report.safetyLeaks.length}**, unsafe actuations **${report.unsafeActuations.length}** — ${safetyClean ? "**all zero; the safety boundary held across every adversarial case.**" : "**NON-ZERO — investigate before any further work.**"}

## By category

${categoryTable(report)}

## The gap, concretely (sample of declined natural utterances)

Each line is an utterance a competent operator would mean unambiguously, which
the exact-match parser declines today:

${missedExamples(report)}

## Honest reading

- The dataset includes ${report.safetyCasesTotal} adversarial safety cases
  (interim transcripts, substring smuggling, cross-profile phrases, conflicting
  recogniser hypotheses). ${safetyClean ? "No unsafe assumptions were observed in this evaluation." : "Resolve the unsafe findings before using this baseline as safety evidence."}
- The **${gap}** coverage gap on natural phrasing is the
  reproducible deficiency that justifies Wave One: a natural-language intent
  layer that proposes a catalog command (and its confidence) *before* the
  deterministic boundary, leaving final-only exact dispatch unchanged.
- Keep the held-out split out of tuning when evaluating a future layer. These
  cases are visible in the repository; the split is a convention, not a blind test.

## Reproduce

\`\`\`sh
cd typescript
node --import tsx tests/support/generateVoiceIntentReport.ts   # regenerate this report
node --import tsx --test tests/voiceIntentBaseline.test.ts      # assert invariants + locked baseline
\`\`\`
`;
}

function main(): void {
  const report = evaluate();
  const markdown = buildMarkdown(report);
  const here = dirname(fileURLToPath(import.meta.url));
  const outPath = resolve(
    here,
    `../../../docs/evidence/voice-intent-baseline-${BASELINE_EDITION}.md`,
  );
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, markdown, "utf8");
  const natural = report.naturalCoverage;
  process.stdout.write(
    `voice-intent baseline: natural coverage ${natural.correct}/${natural.total} (${formatPct(natural.rate)}), ` +
      `wrong-matches ${report.wrongMatches.length}, leaks ${report.safetyLeaks.length}, ` +
      `unsafe actuations ${report.unsafeActuations.length}\nwrote ${outPath}\n`,
  );
}

const entryPoint = process.argv[1];
if (entryPoint && import.meta.url === pathToFileURL(entryPoint).href) main();
